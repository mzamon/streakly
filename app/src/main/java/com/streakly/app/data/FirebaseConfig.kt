package com.streakly.app.data

import android.content.Context
import com.google.firebase.FirebaseApp

/**
 * Firebase is only available once the developer adds google-services.json. Checking first lets the app
 * explain what is missing instead of crashing.
 */
object FirebaseConfig {
    private var appContext: Context? = null

    fun init(context: Context) {
        appContext = context.applicationContext
    }

    fun isReady(): Boolean {
        val ctx = appContext ?: return false
        return try {
            FirebaseApp.getApps(ctx).isNotEmpty()
        } catch (e: Exception) {
            false
        }
    }

    /** Web client id generated by the google-services plugin, or null when Google sign-in is not configured. */
    fun webClientId(): String? {
        val ctx = appContext ?: return null
        val id = ctx.resources.getIdentifier("default_web_client_id", "string", ctx.packageName)
        return if (id == 0) null else ctx.getString(id)
    }
}
